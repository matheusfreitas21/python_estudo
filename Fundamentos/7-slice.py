movieName = "The Matrix"

# 1 - Buscar toda string a partir da primeira posicao
print(movieName[0:])
# 2- Buscar toda string até o ultima posicao
print(movieName[:11])
# 3- Buscar toda string  da terceira até o ultima posicao
print(movieName[2:11]) 
# 4 - Buscar toda a string de 2 em 2 caracteres
print(movieName[::2])

# 5 - Buscar toda a string nos indices impares
print(movieName[1::2])

# 6 - Inverte a string de tras para frente
print(movieName[::-1])  